export function translate(lang, key, vars = {}) {
  const pack = STRINGS[lang] || STRINGS.zh;
  const template = pack[key] ?? STRINGS.zh[key] ?? key;
  return String(template).replace(/\{\{(\w+)\}\}/g, (_, name) => String(vars[name] ?? ''));
}
